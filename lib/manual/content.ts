/** 補足の種類。info=知っておくと良い / warn=気をつける / tip=こつ */
export type ManualCalloutKind = "info" | "warn" | "tip";

/** 手順1つ。uiLabel は「その手順で押す・選ぶ画面上の文字」（逐語・無ければ空） */
export interface ManualStep {
  text: string;
  uiLabel: string;
}

export interface ManualCallout {
  kind: ManualCalloutKind;
  text: string;
}

export interface ManualFaq {
  q: string;
  a: string;
}

/**
 * 章ごとの操作動画。status="planned" のうちは画面に「準備中」と出し、
 * 収録した mp4 を public/manual/videos/ に置いて "ready" に変えると再生できる。
 */
export interface ManualVideo {
  src: string;
  /** 目安の長さ（分）。収録台本 docs/MANUAL-VIDEO-SPEC.md の合計秒数から算出 */
  minutes: number;
  status: "ready" | "planned";
}

export interface ManualChapter {
  /** アンカー（例: "ch3"）。アプリ内は /guide#ch3、静的HTMLは #ch3 */
  id: string;
  /** 章番号の丸数字 */
  no: string;
  /** 章タイトル（番号を含まない） */
  title: string;
  /** 目次に出す短い名前 */
  short: string;
  /** この章で何ができるようになるか（1〜2文） */
  lead: string;
  video: ManualVideo;
  steps: ManualStep[];
  callouts: ManualCallout[];
  faq: ManualFaq[];
}

