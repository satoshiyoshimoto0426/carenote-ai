import { describe, expect, it } from "vitest";
import {
  detectPatterns,
  hasLongDigitRun,
  maskPatterns,
  normalizeDigitSeparators,
} from "./patterns";
import { createPiiVault } from "./vault";

const mask = (text: string) => maskPatterns(text, createPiiVault());

describe("型置換: maskPatterns", () => {
  it("電話番号（ハイフン・括弧・フリーダイヤル）を札に置き換える", () => {
    const { text, findings } = mask(
      "連絡先は090-1234-5678、事業所は06(1234)5678、相談は0120-123-456です。",
    );
    expect(text).toBe("連絡先は〔電話番号1〕、事業所は〔電話番号2〕、相談は〔電話番号3〕です。");
    expect(findings).toContainEqual({ kind: "phone", count: 3 });
  });

  it("同じ番号が2回出ても同じ札になる", () => {
    const { text } = mask("090-1234-5678 に電話。折り返しも 090-1234-5678。");
    expect(text).toBe("〔電話番号1〕 に電話。折り返しも 〔電話番号1〕。");
  });

  it("郵便番号とメールを消す", () => {
    const { text } = mask("〒530-0001 送付先 taro@example.co.jp");
    expect(text).toBe("〔郵便番号1〕 送付先 〔メール1〕");
  });

  it("番地を含む住所を消し、数字の無い地名は残す", () => {
    const { text } = mask("大阪府大阪市北区梅田1-2-3に転居。大阪府の事業所に紹介。");
    expect(text).toBe("〔住所1〕に転居。大阪府の事業所に紹介。");
  });

  // Issue #8（2026-09-25）: 都道府県名の無い住所も、番地の形（1-2-3・1丁目2番3号・123番地）が続けば消す
  it("都道府県名の無い住所（市区町村から番地まで）を消す", () => {
    const { text, findings } = mask(
      "大阪市北区梅田1-2-3に転居。吹田市千里山西1丁目2番3号の長女宅。堺市堺区南瓦町3-1の自宅。三島郡島本町桜井1-2-3。",
    );
    expect(text).toBe("〔住所1〕に転居。〔住所2〕の長女宅。〔住所3〕の自宅。〔住所4〕。");
    expect(findings).toContainEqual({ kind: "address", count: 4 });
  });

  it("都道府県つきの「1丁目2番3号」の形も、番地まで残さず消す", () => {
    const { text } = mask("大阪府大阪市北区梅田1丁目2番3号に住む。");
    expect(text).toBe("〔住所1〕に住む。");
  });

  // 独立審査（2026-09-25）が挙げた取りこぼし: 漢数字の丁目・「2番3号」・「1丁目2-3」の「-3」の残り
  it("漢数字の丁目・「2番3号」・「1丁目2-3」の形も、番地まで残さず消す", () => {
    const { text } = mask(
      // 都道府県つきの規則が先に動いて〔住所1〕になるので、都道府県つきを先頭に置いている
      "大阪府大阪市北区梅田1丁目2-3。大阪市北区梅田一丁目2番3号。北区梅田2番3号。北区梅田1丁目2-3。",
    );
    expect(text).toBe("〔住所1〕。〔住所2〕。〔住所3〕。〔住所4〕。");
  });

  it("番地の形が続かない地名・回数・時刻は消さない（誤って消さない）", () => {
    const src =
      "大阪市北区の事業所に3回訪問。北区で2回、9-12時に面談。堺市内の2か所。町内会3回目。要介護2、血圧130-80。" +
      // 間にひらがなが無く数字1つが続く文（番地の形を「1-2」以上に絞った理由。数字1つでも消す規則だと、ここが消える）
      "大阪市営住宅3階に住む。堺市在住85歳。北区担当2名。";
    const { text, findings } = mask(src);
    expect(text).toBe(src);
    expect(findings).toEqual([]);
  });

  // 独立審査（2026-09-25）が挙げた誤爆。予定の欄とカレンダーの文では札が元へ戻らないので、消すと予定が壊れる。
  // 「村」で終わる名字（中村・田村・木村）が市区町村の「村」に当たる・範囲の書き方「1-2」が時刻・日数・回数と同じ、が原因
  it("予定・通院・測った値の書き方（単位が続く範囲・血圧・第〜回・区分・西暦の日付）は住所として消さない", () => {
    const src =
      "明日中村ケアマネ9-10時来所予定。来週火曜田村医院10-11時受診予定。北区役所9-12時に手続き。" +
      "北区役所2026-10-01訪問予定。木村医師2-3日後再診。堺市内2-3か所。北区内週2-3回利用。" +
      "障害支援区分2-3程度。北区クリニック受診血圧130-80。小学校区1-2年生。北地区第1-2回会議。" +
      "中央市場3-4時。吹田市民病院3-2病棟。";
    const { text, findings } = mask(src);
    expect(text).toBe(src);
    expect(findings).toEqual([]);
  });

  // 再審査（2026-09-25）: 住所のすぐ後ろに建物名（日本生命ビル・本館）が続いても、4桁の番地（2001-3）や
  // 「月」で終わる町名（望月）でも、住所として消す。単位の見張りは2つ区切りの範囲（9-10時）にだけかける
  it("住所の後ろに建物名が続く形・4桁の番地・「月」で終わる町名も消す", () => {
    const { text } = mask(
      "北区梅田1-2-3日本生命ビル。北区梅田1丁目2-3日本ビル。北区梅田123番地日本。三島郡島本町桜井2001-3。佐久市望月263-1。",
    );
    expect(text).toBe(
      "〔住所1〕日本生命ビル。〔住所2〕日本ビル。〔住所3〕日本。〔住所4〕。〔住所5〕。",
    );
  });

  // 3回目の審査（2026-09-25）: 「から」の「か」を「2-3か所」の単位と取り違えて、住所が残っていた
  it("2つ区切りの住所の後ろに「から」が続いても消す", () => {
    const { text } = mask("北区梅田3-1から転居。堺市堺区南瓦町3-1から北区中津へ転居。");
    expect(text).toBe("〔住所1〕から転居。〔住所2〕から北区中津へ転居。");
  });

  it("単位の続く範囲（月1-2回・1-2錠・2-3割・1-2cm・2-3kg・2-3カ所・2-3カ月）と、年-月-日の書き方は消さない", () => {
    const src =
      "中村ケアマネ月1-2回。木村医師処方1-2錠。中村看護師主食2-3割摂取。北区クリニック褥瘡1-2cm。" +
      "中村看護師体重2-3kg減。北区役所2026-1-5訪問。堺市内2-3カ所。北区訪問2-3カ月。北区訪問2-3ケ月。";
    const { text, findings } = mask(src);
    expect(text).toBe(src);
    expect(findings).toEqual([]);
  });

  // 「町名にひらがなを入れない」線引きの見張り。単位の付かない「1-2」を置き、ひらがなを町名に入れると消える形にしてある
  it("市区町村名と番地の形の間にひらがながあれば、住所として消さない", () => {
    const src = "大阪市北区の1-2を確認。";
    expect(mask(src).text).toBe(src);
  });

  it("市区町村名のすぐ後ろの電話番号は、住所ではなく電話番号として消す", () => {
    const { text } = mask("北区事業所090-1234-5678へ連絡。北区包括電話06-1234-5678。");
    expect(text).toBe("北区事業所〔電話番号1〕へ連絡。北区包括電話〔電話番号2〕。");
  });

  // 長い漢字だけの文で手間が爆発しないこと（独立審査 2026-09-25: 先読みの近道が無いと6万字で1秒を超えた）。
  // 余裕を大きく取った上限で、近道が外れたときだけ落ちるようにしてある
  it("市区町村の字だけが6万字並ぶ文でも、置き換えと検出が速く終わる", () => {
    const long = "区".repeat(60000);
    const t0 = performance.now();
    mask(long);
    detectPatterns(long);
    expect(performance.now() - t0).toBeLessThan(1000);
  });

  it("文脈語つきの生年月日と、昭和の年月日を消す", () => {
    const { text } = mask("生年月日：1950年3月4日。昭和25年3月4日生。");
    expect(text).toBe("〔生年月日1〕。〔生年月日2〕生。");
  });

  it("予定の日付は消さない（カレンダー登録と支援経過の日付を壊さない）", () => {
    const { text, findings } = mask("9月12日14時に面談。次回は令和8年10月1日。");
    expect(text).toBe("9月12日14時に面談。次回は令和8年10月1日。");
    expect(findings).toHaveLength(0);
  });

  it("被保険者番号などの8〜12桁を消し、短い数字は残す", () => {
    const { text } = mask("被保険者番号 0123456789、要介護2、利用回数12回");
    expect(text).toBe("被保険者番号 〔番号1〕、要介護2、利用回数12回");
  });

  it("何も無ければ原文のまま・findings は空", () => {
    const r = mask("A様より入浴の希望あり。");
    expect(r.text).toBe("A様より入浴の希望あり。");
    expect(r.findings).toEqual([]);
  });
});

describe("型検出: detectPatterns（漏れ検査用）", () => {
  it("残っている型の種類だけを返す", () => {
    expect(detectPatterns("電話 090-1234-5678")).toEqual(["phone"]);
    expect(detectPatterns("A様と面談")).toEqual([]);
  });
});

describe("表記ゆれ（独立審査 2026-09-11 critical #8・D24）", () => {
  it("ドット区切り・+81・「TEL:」直後の詰めた番号も電話番号として消す", () => {
    const { text } = mask(
      "090.1234.5678 / +81 90-1234-5678 / TEL:0901234-5678 / 電話 06(1234)5678 / 携帯 0901234 5678",
    );
    // 札の番号はルールの適用順（+81 → 一般 → TEL直後）なので順不同。全部消えることを確かめる
    expect(text).not.toMatch(/\d{4}/);
    expect(text.match(/〔電話番号\d〕/g)).toHaveLength(5);
  });

  it("「TEL:」直後でも10〜11桁でなければ電話番号にしない・小数は壊さない", () => {
    expect(mask("TEL:012-345 と 体重52.3kg").text).toBe("TEL:012-345 と 体重52.3kg");
  });

  it("YYYY/M/D と YYYY.M.D の生年月日（文脈語つき）を消す", () => {
    expect(mask("生年月日 1950/3/4、誕生日 1950.03.04").text).toBe("〔生年月日1〕、〔生年月日2〕");
  });

  it("4桁-4桁-4桁（空白・ハイフン）のマイナンバー形を〔番号〕にする", () => {
    expect(mask("番号 1234 5678 9012 と 1234-5678-9012").text).toBe("番号 〔番号1〕 と 〔番号2〕");
  });

  it("normalizeDigitSeparators: 数字の間の長音・ダッシュをハイフンにし、ゼロ幅文字を除く", () => {
    expect(normalizeDigitSeparators("090ー1234−5678\u200bです")).toBe("090-1234-5678です");
    expect(normalizeDigitSeparators("2〜3回")).toBe("2〜3回"); // 波ダッシュは対象外（範囲の意味を保つ）
  });

  it("中黒や複数の空白で区切られた番号も電話番号として消す（CI 審査 2026-09-12）", () => {
    expect(mask("連絡先 090 ・ 1234 ・ 5678 と 06 - 1234 - 5678").text).toBe(
      "連絡先 〔電話番号1〕 と 〔電話番号2〕",
    );
  });

  it("hasLongDigitRun: 区切りを無視して10桁以上なら true、日付・時刻は false", () => {
    expect(hasLongDigitRun("90 ・ 1234 ・ 5678")).toBe(true);
    expect(hasLongDigitRun("90,1234,5678")).toBe(true); // CI 審査 Minor: 読点区切り
    expect(mask("090,1234,5678 と 費用 1,234,567円").text).toBe(
      "〔電話番号1〕 と 費用 1,234,567円",
    );
    expect(hasLongDigitRun("2026-09-11 14:30 に 2026-09-30 10:00 訪問")).toBe(false);
    expect(hasLongDigitRun("90-1234-5678")).toBe(true);
    expect(hasLongDigitRun("0901234-5678")).toBe(true);
    expect(hasLongDigitRun("2026-09-11 14:30 に 2026-09-30")).toBe(false);
    expect(hasLongDigitRun("要介護2・週3回・体重52.3kg")).toBe(false);
  });
});
