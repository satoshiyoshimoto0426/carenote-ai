import { describe, expect, it } from "vitest";
import { maskPii } from "./maskPii";
import { createPiiVault } from "./vault";

/**
 * 黒塗りの速さの見張り（独立審査 2026-10-08 重大1 の再発防止）。
 *
 * なぜ必要か: メールの型の長さに上限が無く、「@ の無い英数字の長い並び」で長さの2乗の時間がかかっていた
 *   （6万字で約11〜15秒）。ログインなしの試行版では誰でも送れる道に乗っていて、Vercel の計算の枠を
 *   使い切って CareNote 本番まで止めうる形だった。型を足す・直すときに同じ形を作り込んだら、ここが赤になる。
 * 入れる文: 送れる長さの上限（合計6万字 ── lib/generation/dispatch.ts）で、型が「始まりの位置ごとに読み直す」
 *   形になりやすい並び（英数字・数字・区切り・点・電話の前置き・都道府県・市区町村・生年月日の言葉）。
 *   直す前は a・digits・dashdigits・zerodash・adot・tel が11〜15秒、直したあとはどれも0.05秒ほど（2026-10-08 手元で測定）。
 *   再審査で、都道府県の無い住所の型も同じ形で遅い（市区町村の後に長い数字・約7〜14秒）と分かり、番地の数字を5桁までにした。
 *   3回目の審査で、短い単位のくり返し（市区町村の字の並び＋番地）も1字あたり数百倍の手間（約1.5秒）と分かり、市区町村の区切り方を
 *   先読みで1通りに決める形にした。700通り（前置き×くり返す字×後ろ）と、前置き15種×短い単位17種＝255通りを6万字で測り、最長0.19秒（2026-10-08）。
 */
const N = 60_000;
const rep = (unit: string) => unit.repeat(Math.ceil(N / unit.length)).slice(0, N);
const HOSTILE: Record<string, string> = {
  英字: rep("a"),
  数字: rep("1"),
  数字とハイフン: rep("1-"),
  ゼロとハイフン: rep("0-"),
  英字と点: rep("a."),
  電話の前置き: rep("TEL0"),
  メールの形: rep("a@a."),
  都道府県: rep("大阪府1"),
  市区町村: rep("市町1-"),
  生年月日: rep("生年月日1"),
  混ぜたもの: rep("a1-.@ +81("),
  // 都道府県の無い住所の型（市区町村の後に長い数字の並び）── 再審査 重大A。直す前は約7〜14秒
  市区町村と長い数字: `${"市".repeat(28)}1-${rep("1").slice(0, N - 32)}時`,
  // NFKC で「⑳」が「20」の2字になる（大きさの検査は NFKC の前の字数で数えるので、黒塗りの中では2倍の長さになる）
  市区町村と丸数字: `${"市".repeat(28)}1-${rep("⑳").slice(0, N - 32)}時`,
  // 短い単位のくり返し（市区町村の字の並び＋番地の形）── 3回目 重大1。区切り方の組み合わせを全部試して1字あたり数百倍の手間（約1.5秒）だった
  市区町村郡のくり返しと番地: rep(`${"市区町村郡".repeat(28)}1-1時`),
  市区町村郡のくり返しと長い番地: rep(`${"市区町村郡".repeat(28)}11111-11111時`),
  市と番地のくり返し: rep(`${"市".repeat(28)}1-2-3`),
};

describe("黒塗りは、送れる上限の長さの意地悪な文でもすぐ終わる", () => {
  for (const [name, text] of Object.entries(HOSTILE)) {
    it(`${name}（${N}字）`, () => {
      const started = performance.now();
      try {
        maskPii(text, [], createPiiVault());
      } catch {
        // 漏れ検査で止まる文もある（数字の長い並びなど）。ここで見るのは時間だけ
      }
      // 直す前は1.5秒〜15秒。CI の遅さを見込んで0.5秒を上限にする（直したあとは手元で0.11秒まで）
      expect(performance.now() - started).toBeLessThan(500);
    });
  }
});
